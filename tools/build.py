"""Build the generated half of the mod from the installed game.

For every franchise in data/franchises/*.json this copies the base game's standard weapon lines
(techs, components, component sets, weapon stats, names) under the franchise's own keys, shows them
only to that franchise's empires, and hides the base-game copies above tier 0 from franchise
empires. Everything is read from the game on this machine, so a game patch only needs a rebuild.

    python tools/build.py                 build into mod/
    python tools/build.py --report        print the tech -> component-set table and stop
    python tools/build.py --game <path>   use another Stellaris install

Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import pdx

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "mod"
DEFAULT_GAME = Path(r"F:\SteamLibrary\steamapps\common\Stellaris")
GEN = "utw_generated"            # every generated file carries this in its name
HEADER = "# GENERATED by tools/build.py from the installed game. Do not edit by hand; edit data/ and rebuild.\n"


# ----------------------------------------------------------------------------- loading
def load_loc(game: Path) -> dict[str, str]:
    loc: dict[str, str] = {}
    pat = re.compile(r'^\s*([\w.\-]+):\d*\s*"(.*)"\s*(?:#.*)?$')
    for f in sorted((game / "localisation" / "english").rglob("*.yml")):
        for line in pdx.read_text(f).splitlines():
            m = pat.match(line)
            if m:
                loc[m.group(1)] = m.group(2)
    return loc


def resolve(loc: dict[str, str], key: str, depth: int = 0) -> str | None:
    val = loc.get(key)
    if val is None or depth > 4:
        return val
    return re.sub(r"\$(\w+)\$", lambda m: resolve(loc, m.group(1), depth + 1) or m.group(0), val)


class Game:
    def __init__(self, path: Path):
        self.path = path
        self.techs = {e.key: e for e in pdx.load_dir(path / "common" / "technology") if e.is_block}
        self.components = []
        for e in pdx.load_dir(path / "common" / "component_templates"):
            if e.is_block and e.key in ("weapon_component_template", "strike_craft_component_template"):
                key = (pdx.field(e.body, "key") or "").strip('"')
                self.components.append((key, e))
        self.sets = {}
        for e in pdx.load_dir(path / "common" / "component_sets"):
            if e.is_block and e.key == "component_set":
                self.sets[(pdx.field(e.body, "key") or "").strip('"')] = e
        self.csv_header: list[str] = []
        self.csv_rows: dict[str, list[str]] = {}
        for f in sorted((path / "common" / "component_templates").glob("*.csv")):
            for line in pdx.read_text(f).splitlines():
                cells = line.split(";")
                if not cells or not cells[0] or cells[0].startswith("#"):
                    continue
                if cells[0].lower() == "key":
                    if f.name == "weapon_components.csv":
                        self.csv_header = cells
                    continue
                if f.name == "weapon_components.csv":
                    self.csv_rows[cells[0]] = cells
        self.loc = load_loc(path)

    def prerequisites(self, tech: str) -> list[str]:
        return pdx.str_list(pdx.field(self.techs[tech].body, "prerequisites"))


# ----------------------------------------------------------------------------- helpers
def renamer(mapping: dict[str, str]):
    """One pass, whole tokens only, longest names first."""
    if not mapping:
        return lambda s: s
    alt = "|".join(re.escape(k) for k in sorted(mapping, key=len, reverse=True))
    pat = re.compile(r"(?<![\w])(" + alt + r")(?![\w])")
    return lambda s: pat.sub(lambda m: mapping[m.group(1)], s)


def strip_comments(text: str) -> str:
    out = []
    for line in text.splitlines():
        i, in_str = 0, False
        while i < len(line):
            if line[i] == '"':
                in_str = not in_str
            elif line[i] == "#" and not in_str:
                line = line[:i].rstrip()
                break
            i += 1
        out.append(line)
    return "\n".join(out)


def add_weight_gate(tech_text: str, gate: str) -> str:
    """Put a `factor = 0` modifier into the tech's weight_modifier block (creating it if absent)."""
    brace = tech_text.index("{")
    body = tech_text[brace + 1: tech_text.rindex("}")]
    for e in pdx.entries(body):
        if e.key == "weight_modifier" and e.is_block:
            new = e.text[: e.text.index("{") + 1] + "\n\t\t" + gate + e.text[e.text.index("{") + 1:]
            return tech_text.replace(e.text, new, 1)
    return tech_text[: tech_text.rindex("}")] + "\tweight_modifier = {\n\t\t" + gate + "\n\t}\n}"


def remove_entries(tech_text: str, names: tuple[str, ...]) -> str:
    brace = tech_text.index("{")
    body = tech_text[brace + 1: tech_text.rindex("}")]
    for e in pdx.entries(body):
        if e.key in names:
            tech_text = tech_text.replace(e.text, "", 1)
    return tech_text


def has_field(tech_text: str, name: str) -> bool:
    body = tech_text[tech_text.index("{") + 1: tech_text.rindex("}")]
    return any(e.key == name for e in pdx.entries(body))


def patch_prerequisites(tech_text: str, alternatives: dict[str, list[str]]) -> str:
    """Let a tech that needs base-game tech T also accept any franchise copy of T."""
    body = tech_text[tech_text.index("{") + 1: tech_text.rindex("}")]
    for e in pdx.entries(body):
        if e.key != "prerequisites" or not e.is_block:
            continue
        inner = strip_comments(e.body)
        out, i = [], 0
        # walk the block: bare/quoted tokens at this level get wrapped, OR blocks get widened in place
        tokens = re.finditer(r'OR\s*=\s*\{([^{}]*)\}|"([^"]+)"|([^\s{}="]+)', inner)
        changed = False
        for m in tokens:
            if m.group(1) is not None:
                names = pdx.str_list("{" + m.group(1) + "}")
                wide = []
                for n in names:
                    wide.append(n)
                    wide.extend(alternatives.get(n, []))
                changed |= len(wide) != len(names)
                out.append("OR = { " + " ".join(f'"{n}"' for n in wide) + " }")
            else:
                n = m.group(2) or m.group(3)
                if n in alternatives:
                    changed = True
                    out.append("OR = { " + " ".join(f'"{x}"' for x in [n] + alternatives[n]) + " }")
                else:
                    out.append(f'"{n}"')
        if changed:
            new = "prerequisites = { " + " ".join(out) + " }"
            tech_text = tech_text.replace(e.text, new, 1)
    return tech_text


def write(path: Path, text: str, bom: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not pdx.check_balanced(text) and path.suffix == ".txt":
        raise SystemExit(f"REFUSED: unbalanced braces in generated {path}")
    path.write_text(text, encoding="utf-8-sig" if bom else "utf-8", newline="\n")


# ----------------------------------------------------------------------------- build
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--game", type=Path, default=DEFAULT_GAME)
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()

    game = Game(args.game)
    core_data = json.loads((ROOT / "data" / "core_lines.json").read_text(encoding="utf-8"))
    lines = core_data["lines"]
    allowed_sets = set(core_data["sets"])
    core: list[str] = []
    for name, techs in lines.items():
        for t in techs:
            if t not in game.techs:
                print(f"WARN core line '{name}': {t} is not in this game version; skipped")
            else:
                core.append(t)
    core_set = set(core)

    # components each core tech unlocks (only components whose every prerequisite is a core tech)
    comps_by_tech: dict[str, list[tuple[str, pdx.Entry]]] = defaultdict(list)
    cloned_components: list[tuple[str, pdx.Entry]] = []
    for key, e in game.components:
        pre = pdx.str_list(pdx.field(e.body, "prerequisites"))
        cset = (pdx.field(e.body, "component_set") or "").strip('"')
        if pre and all(p in core_set for p in pre) and (args.report or cset in allowed_sets):
            cloned_components.append((key, e))
            for p in pre:
                comps_by_tech[p].append((key, e))
    set_of = {k: (pdx.field(e.body, "component_set") or "").strip('"') for k, e in cloned_components}
    cloned_sets = sorted({s for s in set_of.values() if s in game.sets})

    if args.report:
        print("csv columns:", game.csv_header)
        for name, techs in lines.items():
            print(f"\n[{name}]")
            for t in techs:
                if t not in core_set:
                    continue
                sets = sorted({set_of[k] for k, _ in comps_by_tech[t] if set_of[k]})
                tier = pdx.field(game.techs[t].body, "tier")
                print(f"  {t} (tier {tier}) = {resolve(game.loc, t)!r}")
                for s in sets:
                    print(f"      set {s} = {resolve(game.loc, s)!r}")
        return 0

    franchises = [json.loads(f.read_text(encoding="utf-8")) for f in sorted((ROOT / "data" / "franchises").glob("*.json"))]
    if not franchises:
        raise SystemExit("no franchise files in data/franchises")

    tech_out, comp_out, set_out, csv_out, loc_out, event_out = [HEADER], [HEADER], [HEADER], [], [], []
    alternatives: dict[str, list[str]] = defaultdict(list)
    comp_by_src: dict[Path, list[str]] = defaultdict(list)   # base-game file -> copied components
    fallback_names = 0
    summary = []

    for fr in franchises:
        fid, pre, label = fr["id"], fr["prefix"], fr["label"]
        tmap = {t: f"{pre}_{t}" for t in core}
        cmap = {k: f"{pre.upper()}_{k}" for k, _ in cloned_components}
        smap = {s: f"{pre.upper()}_{s}" for s in cloned_sets}
        ren = renamer({**tmap, **cmap, **smap})
        gate = f"modifier = {{ factor = 0 utw_is_{fid} = no }}"
        names, descs, stat = fr.get("names", {}), fr.get("descriptions", {}), fr.get("stats", {})
        line_of = {t: ln for ln, ts in lines.items() for t in ts}

        tech_out.append(f"\n##### {label} #####\n")
        for t in core:
            alternatives[t].append(tmap[t])
            txt = strip_comments(game.techs[t].text)
            txt = remove_entries(txt, ("technology_swap", "start_tech"))
            had_icon = has_field(txt, "icon")
            txt = ren(txt)
            if not had_icon:
                txt = txt[: txt.index("{") + 1] + f"\n\ticon = {t}" + txt[txt.index("{") + 1:]
            txt = add_weight_gate(txt, gate)
            tech_out.append(re.sub(r"\n\s*\n\s*\n+", "\n\n", txt) + "\n")
            vn = resolve(game.loc, t) or t
            main_sets = [set_of[k] for k, _ in comps_by_tech[t] if set_of[k] in names]
            if t in names:
                loc_out.append((tmap[t], names[t]))
            elif main_sets:
                n = names[main_sets[0]]
                loc_out.append((tmap[t], n if n.endswith("s") else n + "s"))
            else:
                fallback_names += 1
                loc_out.append((tmap[t], f"{label} {vn}"))
            loc_out.append((tmap[t] + "_desc", descs.get(t) or resolve(game.loc, t + "_desc") or ""))

        comp_out.append(f"\n##### {label} #####\n")
        for key, e in cloned_components:
            txt = strip_comments(e.text)
            up = (pdx.field(e.body, "upgrades_to") or "").strip('"')
            if up and up not in cmap:
                txt = remove_entries(txt, ("upgrades_to",))
            comp_by_src[e.path].append(f"# {label}\n" + re.sub(r"\n\s*\n+", "\n", ren(txt)) + "\n")
            s = set_of[key]
            new_set_name = names.get(s) or (f"{label} {resolve(game.loc, s)}" if resolve(game.loc, s) else None)
            vname, vset = resolve(game.loc, key), resolve(game.loc, s)
            if vname and vset and new_set_name and vset in vname:
                loc_out.append((cmap[key], vname.replace(vset, new_set_name)))
            elif vname:
                loc_out.append((cmap[key], f"{label} {vname}"))
            if key in game.csv_rows:
                row = list(game.csv_rows[key])
                row[0] = cmap[key]
                mult = stat.get(line_of_component(key, e, line_of), {})
                for col, m in mult.items():
                    if col in game.csv_header:
                        i = game.csv_header.index(col)
                        try:
                            row[i] = f"{float(row[i]) * m:.2f}"
                        except (ValueError, IndexError):
                            pass
                csv_out.append(";".join(row))

        set_out.append(f"\n##### {label} #####\n")
        for s in cloned_sets:
            set_out.append(ren(strip_comments(game.sets[s].text)) + "\n")
            vn = resolve(game.loc, s)
            if s in names:
                loc_out.append((smap[s], names[s]))
            else:
                fallback_names += 1
                loc_out.append((smap[s], f"{label} {vn or s}"))
            d = resolve(game.loc, s + "_DESC")
            if d:
                loc_out.append((smap[s] + "_DESC", descs.get(s) or d))

        tier0 = [tmap[t] for t in core if (pdx.field(game.techs[t].body, "tier") or "").strip() == "0"]
        event_out.append((fid, tier0))
        summary.append(f"{label}: {len(core)} techs, {len(cloned_components)} components, {len(cloned_sets)} sets, {len(tier0)} granted at start")

    # --- base-game files: hide core techs above tier 0 from franchise empires; widen dependants
    vanilla_gate = "modifier = { factor = 0 utw_is_franchise_empire = yes }"
    by_file: dict[Path, list[tuple[str, str]]] = defaultdict(list)
    gated = widened = 0
    for key, e in game.techs.items():
        new = e.text
        if key in core_set:
            if (pdx.field(e.body, "tier") or "").strip() != "0":
                new = add_weight_gate(new, vanilla_gate)
                gated += 1
        else:
            new = patch_prerequisites(new, alternatives)
            widened += new != e.text
        if new != e.text:
            by_file[e.path].append((e.text, new))
    for old in (MOD / "common" / "technology").glob("*.txt"):
        old.unlink()
    for path, edits in by_file.items():
        text = pdx.read_text(path)
        for old, new in edits:
            if text.count(old) != 1:
                raise SystemExit(f"REFUSED: cannot place edit uniquely in {path.name}")
            text = text.replace(old, new, 1)
        write(MOD / "common" / "technology" / path.name,
              "# GENERATED by tools/build.py: the base game's file with franchise gates added. Rebuild after a game patch.\n" + text)

    write(MOD / "common" / "technology" / f"zz_{GEN}_franchise_techs.txt", "\n".join(tech_out))
    # One output file per base-game source file, each opening with that file's own @variables:
    # a variable defined at the top of a base-game file exists only inside that file.
    for old in (MOD / "common" / "component_templates").glob(f"zz_{GEN}_*.txt"):
        old.unlink()
    for src, blocks in sorted(comp_by_src.items()):
        local_vars = [e.text for e in pdx.entries(strip_comments(pdx.read_text(src))) if e.key.startswith("@") and not e.is_block]
        write(MOD / "common" / "component_templates" / f"zz_{GEN}_{src.stem}.txt",
              HEADER + "\n".join(local_vars) + "\n\n" + "\n".join(blocks))
    write(MOD / "common" / "component_sets" / f"zz_{GEN}_franchise_sets.txt", "\n".join(set_out))
    csv_path = MOD / "common" / "component_templates" / f"zz_{GEN}_franchise_weapons.csv"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    csv_path.write_text("# GENERATED by tools/build.py;\n" + ";".join(game.csv_header) + "\n" + "\n".join(csv_out) + "\n",
                        encoding="utf-8", newline="\n")

    ev = [HEADER, "namespace = utw_start\n"]
    ids = []
    for n, (fid, tier0) in enumerate(event_out, start=1):
        ids.append(f"utw_start.{n}")
        gives = "\n".join(f"\t\tgive_technology = {{ tech = {t} message = no }}" for t in tier0)
        ev.append(f"# {fid}: the franchise's own tier-0 weapons, given once at game start\n"
                  f"country_event = {{\n\tid = utw_start.{n}\n\thide_window = yes\n\tis_triggered_only = yes\n"
                  f"\ttrigger = {{ utw_is_{fid} = yes }}\n\timmediate = {{\n{gives}\n\t}}\n}}\n")
    write(MOD / "events" / f"{GEN}_start.txt", "\n".join(ev))
    write(MOD / "common" / "on_actions" / f"{GEN}_on_actions.txt",
          HEADER + "on_game_start_country = {\n\tevents = {\n" + "".join(f"\t\t{i}\n" for i in ids) + "\t}\n}\n")

    # --- who counts as which franchise, and the origin a player picks to be one
    trig = [HEADER]
    orig = [HEADER]
    for fr in franchises:
        fid = fr["id"]
        trig.append(f"utw_is_{fid} = {{\n\tOR = {{\n\t\thas_origin = origin_utw_{fid}\n\t\thas_country_flag = utw_{fid}\n\t}}\n}}\n")
        o = fr["origin"]
        orig.append(
            f"origin_utw_{fid} = {{\n\tis_origin = yes\n\ticon = \"{o['icon']}\"\n\tpicture = {o['picture']}\n\n"
            "\tplayable = { always = yes }\n\tpossible = { is_nomadic = no }\n\n"
            f"\tdescription = \"origin_tooltip_utw_{fid}_effects\"\n\n"
            "\t# random empires do not roll this; prescripted franchise empires use it\n"
            "\trandom_weight = { base = 0 }\n}\n")
        loc_out.append((f"origin_utw_{fid}", o["name"]))
        loc_out.append((f"origin_utw_{fid}_desc", o["desc"]))
        loc_out.append((f"origin_tooltip_utw_{fid}_effects", o["effects"]))
    trig.append("utw_is_franchise_empire = {\n\tOR = {\n" + "".join(f"\t\tutw_is_{fr['id']} = yes\n" for fr in franchises) + "\t}\n}\n")
    write(MOD / "common" / "scripted_triggers" / f"{GEN}_triggers.txt", "\n".join(trig))
    write(MOD / "common" / "governments" / "civics" / f"{GEN}_origins.txt", "\n".join(orig))

    # --- ready-made empires: a base-game prescripted empire's valid shape with our names, origin and ship look
    emp_file = ROOT / "data" / "empires.json"
    n_emp = 0
    if emp_file.exists():
        templates = {e.key: e for e in pdx.load_dir(game.path / "prescripted_countries") if e.is_block}
        drop = ("name", "adjective", "spawn_enabled", "ignore_portrait_duplication", "ship_prefix", "playable",
                "origin", "initializer", "planet_name", "system_name", "graphical_culture", "flag", "advisor_voice_type")
        emp = [HEADER]
        for em in json.loads(emp_file.read_text(encoding="utf-8"))["empires"]:
            if em["template"] not in templates:
                print(f"WARN empire {em['key']}: template {em['template']} not in this game; skipped")
                continue
            k = f"utw_{em['key']}"
            txt = remove_entries(strip_comments(templates[em["template"]].text), drop)
            body = txt[txt.index("{") + 1: txt.rindex("}")]
            for e in pdx.entries(body):
                if e.key == "species" and e.is_block:
                    new = e.text
                    for fld, lk in (("name", "species_name"), ("plural", "species_plural"), ("adjective", "species_adjective")):
                        new = re.sub(r'(?<![\w])(' + fld + r'\s*=\s*)"[^"]*"', rf'\1"PRESCRIPTED_{lk}_{k}"', new, count=1)
                    txt = txt.replace(e.text, new, 1)
                elif e.key == "ruler" and e.is_block:
                    new = re.sub(r'(?<![\w])(name\s*=\s*)"[^"]*"', rf'\1"PRESCRIPTED_ruler_name_{k}"', e.text, count=1)
                    txt = txt.replace(e.text, new, 1)
                elif e.key == "empire_flag" and e.is_block and em.get("colors"):
                    c = em["colors"]
                    new = re.sub(r"colors\s*=\s*\{[^}]*\}", f'colors={{ "{c[0]}" "{c[1]}" "null" "null" }}', e.text, count=1)
                    txt = txt.replace(e.text, new, 1)
            origin = f"origin_utw_{em['franchise']}" if em.get("franchise") else "origin_default"
            head = (f'\n\tname = "EMPIRE_DESIGN_{k}"\n\tadjective = "PRESCRIPTED_adjective_{k}"\n\tspawn_enabled = yes\n'
                    f'\tignore_portrait_duplication = yes\n\tship_prefix = "PRESCRIPTED_ship_prefix_{k}"\n\torigin = "{origin}"\n'
                    f'\tplanet_name = "PRESCRIPTED_planet_name_{k}"\n\tsystem_name = "PRESCRIPTED_system_name_{k}"\n'
                    f'\tgraphical_culture = "{em["ship_look"]}"\n')
            txt = k + " = {" + head + txt[txt.index("{") + 1:]
            emp.append(f"# {em['name']} (shape of base-game '{em['template']}', ship look from Workshop mod {em.get('mod', '?')})\n"
                       + re.sub(r"\n\s*\n+", "\n", txt) + "\n")
            sp = em["species"]
            for lk, val in ((f"EMPIRE_DESIGN_{k}", em["name"]), (f"EMPIRE_DESIGN_{k}_desc", em.get("desc", "")),
                            (f"PRESCRIPTED_adjective_{k}", em["adjective"]), (f"PRESCRIPTED_ship_prefix_{k}", em["prefix"]),
                            (f"PRESCRIPTED_species_name_{k}", sp[0]), (f"PRESCRIPTED_species_plural_{k}", sp[1]),
                            (f"PRESCRIPTED_species_adjective_{k}", sp[2]), (f"PRESCRIPTED_planet_name_{k}", em["homeworld"]),
                            (f"PRESCRIPTED_system_name_{k}", em["system"]), (f"PRESCRIPTED_ruler_name_{k}", em["ruler"])):
                loc_out.append((lk, val))
            n_emp += 1
        write(MOD / "prescripted_countries" / f"{GEN}_empires.txt", "\n".join(emp))
    summary.append(f"ready-made empires: {n_emp}")

    seen, loc_lines = set(), ["l_english:"]
    for k, v in loc_out:
        if k in seen or v is None:
            continue
        seen.add(k)
        v = v.replace("\r", "").replace("\n", "\\n")
        v = re.sub(r'(?<!\\)"', r'\\"', v)
        loc_lines.append(f' {k}:0 "{v}"')
    write(MOD / "localisation" / "english" / f"{GEN}_l_english.yml", "\n".join(loc_lines) + "\n", bom=True)

    print("game:", args.game)
    for s in summary:
        print(" ", s)
    print(f"  base-game techs hidden from franchise empires: {gated}")
    print(f"  techs whose prerequisites now accept a franchise copy: {widened}")
    print(f"  base-game tech files replaced: {sorted(p.name for p in by_file)}")
    print(f"  weapon stat rows written: {len(csv_out)}; names using the fallback pattern: {fallback_names}")
    return 0


def line_of_component(key: str, e: pdx.Entry, line_of: dict[str, str]) -> str:
    for p in pdx.str_list(pdx.field(e.body, "prerequisites")):
        if p in line_of:
            return line_of[p]
    return ""


if __name__ == "__main__":
    raise SystemExit(main())
