"""Write the Crossover mod list for the game.

Reads docs/conflict_map.json (run tools/scan_mods.py first) and data/playset.json, registers any Workshop
mod the launcher has not registered yet (a ugc_<id>.mod file in the game's user folder), and writes
dlc_load.json so the game loads the chosen mods with Crossverse last.

    python tools/make_playset.py            write the list
    python tools/make_playset.py --dry      only print what would be enabled
    python tools/make_playset.py --only     enable Crossverse alone
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
USER = Path.home() / "Documents" / "Paradox Interactive" / "Stellaris"
WORKSHOP = Path(r"F:\SteamLibrary\steamapps\workshop\content\281990")
OURS = "mod/crossverse.mod"


def major(version: str) -> int | None:
    m = re.search(r"(\d+)", version or "")
    return int(m.group(1)) if m else None


def classify(m: dict) -> str:
    rep = len(m["replaces_vanilla_files"])
    tech = m["adds"].get("common/technology", 0)
    sizes = m["adds"].get("common/ship_sizes", 0)
    redefined = sum(len(v) for v in m["overrides_vanilla_objects"].values())
    if rep > 150:
        return "conversion"
    if tech or sizes or rep > 3 or redefined > 5:
        return "gameplay"
    return "cosmetic"


def register(mod_id: str) -> bool:
    """Create ugc_<id>.mod the way the launcher does. Returns False when the mod has no descriptor."""
    target = USER / "mod" / f"ugc_{mod_id}.mod"
    if target.exists():
        return True
    src = WORKSHOP / mod_id / "descriptor.mod"
    if not src.exists():
        return False
    text = src.read_text(encoding="utf-8-sig", errors="replace").rstrip()
    text = re.sub(r'^\s*(path|archive|remote_file_id)\s*=.*$', "", text, flags=re.M).rstrip()
    text += f'\npath="{(WORKSHOP / mod_id).as_posix()}"\nremote_file_id="{mod_id}"\n'
    target.write_text(text, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--only", action="store_true")
    args = ap.parse_args()

    chosen: list[dict] = []
    if not args.only:
        scan = json.loads((ROOT / "docs" / "conflict_map.json").read_text(encoding="utf-8"))
        rules = json.loads((ROOT / "data" / "playset.json").read_text(encoding="utf-8"))
        include, exclude = rules["include"], rules["exclude"]
        skipped = []
        for m in scan["mods"]:
            if m.get("empty"):
                continue
            mid = m["id"]
            if mid in exclude:
                skipped.append((m["name"], exclude[mid]))
                continue
            if mid in include:
                chosen.append(m)
                continue
            kind = classify(m)
            v = major(m["supported_version"])
            if kind != "cosmetic":
                skipped.append((m["name"], kind))
            elif v is not None and v < 4:
                skipped.append((m["name"], f"built for {m['supported_version']}"))
            else:
                chosen.append(m)
        chosen.sort(key=lambda m: m["name"].lower())
        print(f"enabled: {len(chosen)} Workshop mods + Crossverse; left out: {len(skipped)}")
        looks: dict[str, list[str]] = {}
        for m in chosen:
            for g in m["graphical_cultures"]:
                looks.setdefault(g.lower(), []).append(m["name"])
        for g, who in sorted(looks.items()):
            if len(who) > 1:
                print(f"  ship look '{g}' is defined by {len(who)} enabled mods: {'; '.join(who)}")
        print(f"  ship looks available: {len(looks)}")
        (ROOT / "docs").mkdir(exist_ok=True)
        with open(ROOT / "docs" / "playset_crossover.md", "w", encoding="utf-8", newline="\n") as f:
            f.write("# Crossover mod list\n\nGenerated by `tools/make_playset.py`. Crossverse loads last.\n\n## Enabled\n\n")
            for m in chosen:
                f.write(f"- {m['name']} ({m['id']}), for {m['supported_version']}\n")
            f.write("\n## Left out\n\n")
            for name, why in sorted(skipped):
                f.write(f"- {name}: {why}\n")

    if args.dry:
        return 0
    enabled = []
    for m in chosen:
        if register(m["id"]):
            enabled.append(f"mod/ugc_{m['id']}.mod")
        else:
            print(f"  WARN no descriptor for {m['name']} ({m['id']}); not enabled")
    enabled.append(OURS)
    target = USER / "dlc_load.json"
    if target.exists():
        shutil.copy2(target, USER / f"dlc_load.json.bak-{datetime.now():%Y-%m-%d_%H%M%S}")
        old = json.loads(target.read_text(encoding="utf-8"))
    else:
        old = {}
    target.write_text(json.dumps({"enabled_mods": enabled, "disabled_dlcs": old.get("disabled_dlcs", [])}), encoding="utf-8")
    print(f"wrote {target} with {len(enabled)} mods")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
